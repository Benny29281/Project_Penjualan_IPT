CREATE TABLE IF NOT EXISTS settings (key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS users (
    id INTEGER PRIMARY KEY, role TEXT NOT NULL, login TEXT NOT NULL, password TEXT NOT NULL,
    name TEXT NOT NULL, blocked INTEGER NOT NULL DEFAULT 0, cart TEXT NOT NULL DEFAULT '{}',
    created TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP, UNIQUE(role,login)
);
CREATE TABLE IF NOT EXISTS products (
    id INTEGER PRIMARY KEY, category TEXT NOT NULL, name_en TEXT NOT NULL, name_id TEXT DEFAULT '',
    name_zh TEXT DEFAULT '', name_ko TEXT DEFAULT '', flavour TEXT DEFAULT '', edition TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'draft', images TEXT NOT NULL DEFAULT '[]', demo INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS variants (
    id INTEGER PRIMARY KEY, product_id INTEGER NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    unit TEXT NOT NULL, price INTEGER NOT NULL DEFAULT 0, origin INTEGER NOT NULL DEFAULT 0,
    stock INTEGER NOT NULL DEFAULT 0, UNIQUE(product_id,unit)
);
CREATE TABLE IF NOT EXISTS orders (
    id INTEGER PRIMARY KEY, number TEXT NOT NULL UNIQUE, customer_id INTEGER REFERENCES users(id),
    name TEXT NOT NULL, phone TEXT NOT NULL, address TEXT NOT NULL, notes TEXT NOT NULL, status TEXT NOT NULL,
    subtotal INTEGER NOT NULL, terea INTEGER NOT NULL, device INTEGER, extra INTEGER NOT NULL DEFAULT 0, total INTEGER NOT NULL,
    age_statement TEXT NOT NULL, age_at TEXT NOT NULL, qr TEXT NOT NULL, locale TEXT NOT NULL,
    tracking TEXT DEFAULT '', internal_note TEXT DEFAULT '', paid_by INTEGER REFERENCES users(id), paid_at TEXT,
    demo INTEGER NOT NULL, created TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS order_items (
    id INTEGER PRIMARY KEY, order_id INTEGER NOT NULL REFERENCES orders(id), variant_id INTEGER,
    names TEXT NOT NULL, category TEXT NOT NULL, edition TEXT NOT NULL, unit TEXT NOT NULL, qty INTEGER NOT NULL, price INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS timeline (
    id INTEGER PRIMARY KEY, order_id INTEGER NOT NULL REFERENCES orders(id), actor TEXT NOT NULL,
    status TEXT NOT NULL, created TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS audit (
    id INTEGER PRIMARY KEY, actor TEXT NOT NULL, action TEXT NOT NULL, detail TEXT NOT NULL, created TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS price_history (
    id INTEGER PRIMARY KEY, variant_id INTEGER NOT NULL, product TEXT NOT NULL, unit TEXT NOT NULL,
    actor TEXT NOT NULL, old INTEGER NOT NULL, new INTEGER NOT NULL, created TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS attempts (scope TEXT NOT NULL, time INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS attempts_scope ON attempts(scope,time);
CREATE INDEX IF NOT EXISTS orders_customer ON orders(customer_id,created);
CREATE INDEX IF NOT EXISTS orders_phone ON orders(phone);
CREATE INDEX IF NOT EXISTS items_order ON order_items(order_id);
CREATE TABLE IF NOT EXISTS blocked_phones (phone TEXT PRIMARY KEY);
CREATE TABLE IF NOT EXISTS guest_carts (
    token TEXT PRIMARY KEY, cart TEXT NOT NULL, touched INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS guest_carts_touched ON guest_carts(touched);
CREATE TABLE IF NOT EXISTS uploads (
    id TEXT PRIMARY KEY, mime TEXT NOT NULL, kind TEXT NOT NULL
);
